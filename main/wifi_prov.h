#pragma once

#include <string>

// ---------------------------------------------------------------------------
// 配网信息管理（网页配网方案）
//
// 配网方式已经改成「手机扫码 → 网页填写」，见 web_portal.h。
// 这个模块只保留配网信息的读写和恢复出厂，不再包含蓝牙相关代码。
//
// 恢复出厂：开机时按住 BOOT 键（默认 GPIO0）3 秒，会清除已保存的配网信息
//          和用户数据，下次启动重新进入网页配网模式。
// ---------------------------------------------------------------------------

// 是否已经配过网（WiFi 驱动里有非空的 STA 配置）
bool prov_is_provisioned();

// 从 WiFi 驱动的配置里读取 STA 凭据；没配过网时返回 false
bool prov_load_credentials(std::string& ssid, std::string& password);

// 清除配网信息（下次开机会重新进入网页配网）
void prov_reset();

// 开机时检测"恢复出厂"按键是否被长按
bool prov_detect_reset_request();
