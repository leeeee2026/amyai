#pragma once

#include <string>

// ---------------------------------------------------------------------------
// 本地"秒回"提示
//
// 目的不是替代云端识别，而是**降低主观延迟**：
// 用户说的如果是按摩控制类的话，先立刻播一声「好的」，
// 然后照常走云端 ASR→LLM→TTS 给出完整回复。
//
// 这样用户等待时听到"好的"就不会觉得没反应。
// ---------------------------------------------------------------------------

// 这句话看起来是不是"按摩控制类"（部位/力度/角度/热敷/速度/时间/起停/手法）
bool local_is_control(const std::string& text);

// 是不是"停止音乐"的指令。
// 判定从严：必须是短句（<=10 字）且明确含停止词，避免把闲聊误判成停止。
bool local_is_stop_command(const std::string& text);

// 异步播放「好的」应答音（不阻塞；延迟 500ms 再播）
void local_play_ack();

// 异步播放「好的，马上为您调整」（本地命令词命中时用；同样延迟 500ms）
void local_play_ok();

// 播放「网络还没连上，请稍等」提示音（本地音频，不依赖网络；有 15 秒冷却，避免刷屏）
void local_play_no_net();
